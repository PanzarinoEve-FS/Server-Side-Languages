const add = (a, b) => {
    return a + b;
}

const subtract = (a, b) => {
    return a - b;
}

const multiply = (a, b) => {
    return a * b;
}

const divide = (a, b) => {
    return a / b;
}

const sqrt = (num) => {
    return Math.sqrt(num);
}

const max = (a, b) => {
    return Math.max(a, b);
}

module.exports = {
    add,
    subtract,
    multiply,
    divide,
    sqrt,
    max
}
